"""Hand the catalog to the kb: a seeds file for `kb seed --file`, and incentive/form rows.

Seeds get the full text of every program page and form into the kb lake for search and citation.
load_kb writes the structured side (kb.upsert_incentive / upsert_form / link_form). It doesn't add
criteria yet: kb.add_criterion creates a new row on every call, so re-running would duplicate them.
"""

import json
from datetime import datetime

from . import parse

SEED_AUTHORITIES = {"statute", "regulation", "form", "form_instructions", "program_page"}


def _toml(value) -> str:
    """TOML literal for a string or list of strings (JSON escapes are valid TOML basic-string escapes)."""
    if isinstance(value, list):
        return "[" + ", ".join(_toml(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=False)


def seed_entries(catalog: dict) -> list[dict]:
    """One kb seed per URL: each program page, its form PDFs and instructions, and linked statutes and program pages."""
    entries: dict[str, dict] = {}

    def add(url: str | None, authority: str, program: dict) -> None:
        if not url:
            return
        entry = entries.get(url)
        if entry is None:
            entries[url] = entry = {
                "url": url, "authority": authority, "jurisdiction": program["jurisdiction"],
                "agency": program.get("agency"), "tags": [],
            }
        for tag in [program["id"], *program.get("niches", [])]:
            if tag not in entry["tags"]:
                entry["tags"].append(tag)

    for program in catalog["programs"]:
        add(program["url"], parse.authority(program["url"]), program)
        facts = program.get("facts") or {}
        for form in facts.get("forms", []):
            add(form.get("pdf"), "form", program)
            add(form.get("instructions"), "form_instructions", program)
        for link in [*facts.get("links", []), *program.get("links", [])]:
            if link["authority"] in SEED_AUTHORITIES:
                add(link["url"], link["authority"], program)
    return list(entries.values())


def kb_seeds(catalog: dict) -> str:
    lines = [
        f"# Generated by `legal-research seeds` from the catalog of {catalog['generated_at']}. Do not edit.",
        "# Crawl into the kb: cd kb && uv run kb seed --file ../research/legal/data/kb-seeds.toml",
        "",
    ]
    for entry in seed_entries(catalog):
        lines.append("[[source]]")
        for key in ("url", "authority", "jurisdiction", "agency", "tags"):
            if entry.get(key):
                lines.append(f"{key} = {_toml(entry[key])}")
        lines.append("")
    return "\n".join(lines)


def incentive_fields(program: dict) -> dict:
    facts = program.get("facts") or {}
    hints = facts.get("hints") or {}
    claims = program.get("claims") or []
    fetched = (program.get("page") or {}).get("fetched_at")
    benefit = {"amount_text": facts.get("amount") or None, "claims": claims[0] if claims else None, "niches": program.get("niches")}
    return {
        "name": program["name"],
        "kind": program["kind"],
        "jurisdiction": program["jurisdiction"],
        "agency": program.get("certifying_agency") or program.get("agency"),
        "summary": facts.get("eligibility") or facts.get("summary") or program.get("note") or None,
        "tax_types": program.get("tax_types") or [],
        "refundable": hints.get("refundable"),
        "requires_preapproval": program.get("requires_preapproval"),
        "status": program["status"],
        "benefit": {k: v for k, v in benefit.items() if v},
        "last_verified_at": datetime.fromisoformat(fetched) if fetched and program["page"].get("status") == "ok" else None,
    }


def load_kb(catalog: dict, kb, tax_year: int, log=lambda message: None) -> dict[str, int]:
    """Upsert every program as a kb incentive and every coded form as a kb form revision for tax_year."""
    counts = {"incentives": 0, "forms": 0}
    for program in catalog["programs"]:
        kb.upsert_incentive(program["id"], **incentive_fields(program))
        counts["incentives"] += 1
        for form in (program.get("facts") or {}).get("forms", []):
            if not (form.get("pdf") or form.get("instructions")):
                continue
            kb.upsert_form(
                form["code"], tax_year, title=form.get("title") or None, agency=program.get("agency"),
                pdf=form.get("pdf"), instructions=form.get("instructions"),
            )
            kb.link_form(program["id"], form["code"], tax_year, role="claim")
            counts["forms"] += 1
    log(f"kb: {counts['incentives']} incentives, {counts['forms']} form links")
    return counts
